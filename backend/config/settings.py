# Database
# Set DB_ENGINE=postgresql and provide every DB_* variable to use PostgreSQL.
# SQLite remains the local fallback when DB_ENGINE is unset or set to sqlite.
DB_ENGINE = os.environ.get('DB_ENGINE', 'sqlite').strip().lower()

if DB_ENGINE == 'sqlite':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': os.environ.get('DB_SQLITE_PATH', BASE_DIR / 'db.sqlite3'),
        }
    }
elif DB_ENGINE == 'postgresql':
    required_db_variables = ('DB_NAME', 'DB_USER', 'DB_PASSWORD', 'DB_HOST', 'DB_PORT')
    missing_db_variables = [
        name for name in required_db_variables if not os.environ.get(name)
    ]
    if missing_db_variables:
        from django.core.exceptions import ImproperlyConfigured

        raise ImproperlyConfigured(
            'DB_ENGINE=postgresql requires: ' + ', '.join(missing_db_variables)
        )

    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': os.environ['DB_NAME'],
            'USER': os.environ['DB_USER'],
            'PASSWORD': os.environ['DB_PASSWORD'],
            'HOST': os.environ['DB_HOST'],
            'PORT': os.environ['DB_PORT'],
            'OPTIONS': {
                'sslmode': os.environ.get('DB_SSLMODE', 'prefer' if DEBUG else 'verify-full'),
                **({'sslrootcert': os.environ['DB_SSLROOTCERT']} if os.environ.get('DB_SSLROOTCERT') else {}),
            },
        }
    }
else:
    from django.core.exceptions import ImproperlyConfigured

    raise ImproperlyConfigured(
        f"Unsupported DB_ENGINE '{DB_ENGINE}'. Use 'postgresql' or 'sqlite'."
    )


